const express = require('express')
const controller = require('../controllers/taskController')
const attachments = require('../controllers/attachmentController')
const { authenticate } = require('../middleware/auth')
const { uploadAttachment } = require('../middleware/upload')
const router = express.Router()
const handle = (fn) => (req, res, next) => fn(req, res).catch(next)

router.use(authenticate)
router.get('/:id/attachments', attachments.requireTaskAccess, handle(attachments.list))
router.post('/:id/attachments', attachments.requireTaskAccess, uploadAttachment, handle(attachments.upload))
router.get('/:id/attachments/:attachmentId', attachments.requireTaskAccess, handle(attachments.download))
router.delete('/:id/attachments/:attachmentId', attachments.requireTaskAccess, handle(attachments.remove))
router.patch('/:id', handle(controller.update))
router.delete('/:id', handle(controller.remove))
router.get('/:id/comments', handle(controller.comments))
router.post('/:id/comments', handle(controller.addComment))
router.delete('/:id/comments/:commentId', handle(controller.removeComment))
module.exports = router
