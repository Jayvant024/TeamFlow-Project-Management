const express = require('express')
const controller = require('../controllers/projectController')
const tasks = require('../controllers/taskController')
const { authenticate } = require('../middleware/auth')
const router = express.Router()
const handle = (fn) => (req, res, next) => fn(req, res).catch(next)

router.use(authenticate)
router.get('/', handle(controller.list))
router.post('/', handle(controller.create))
router.get('/:id', handle(controller.getOne))
router.patch('/:id', handle(controller.update))
router.delete('/:id', handle(controller.remove))
router.get('/:id/users', handle(controller.searchUsers))
router.post('/:id/members', handle(controller.addMember))
router.delete('/:id/members/:userId', handle(controller.removeMember))
router.get('/:projectId/tasks', handle(tasks.list))
router.post('/:projectId/tasks', handle(tasks.create))
module.exports = router
